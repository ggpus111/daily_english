HERE = Path(__file__).parent


def main():
    candidates = json.loads((HERE / "data" / "word_candidates.json").read_text(encoding="utf-8"))
    advanced = [item["word"] for item in candidates if item["level"] == "advanced"]
    missing = [word for word in advanced if word not in ADVANCED]
    extra = [word for word in ADVANCED if word not in advanced]
    assert not missing, f"뜻이 없는 고급 단어: {missing}"
    path = HERE / "words_draft.json"
    draft = json.loads(path.read_text(encoding="utf-8"))
    for word in advanced:
        meaning, english, korean = ADVANCED[word]
        draft["words"][word] = [word, meaning]
        draft["own_examples"][word] = [english, korean]
    text = path.read_text(encoding="utf-8")
    nl = "\r\n" if "\r\n" in text else "\n"
    # 원래 모양(키마다 한 줄)을 지킨다.
    one = lambda value: json.dumps(value, ensure_ascii=False)
    parts = []
    for key, value in draft.items():
        if isinstance(value, dict):
            rows = ("," + nl).join(f"    {one(k)}: {one(v)}" for k, v in value.items())
            parts.append(f"  {one(key)}: {{{nl}{rows}{nl}  }}")
        elif isinstance(value, list):
            rows = ("," + nl).join(f"    {one(row)}" for row in value)
            parts.append(f"  {one(key)}: [{nl}{rows}{nl}  ]")
        else:
            parts.append(f"  {one(key)}: {one(value)}")
    path.write_text("{" + nl + ("," + nl).join(parts) + nl + "}" + nl, encoding="utf-8", newline="")
    print(f"고급 {len(advanced)}개 뜻·예문을 words_draft.json에 넣음" + (f" (목록에 없어 안 쓴 원고 {len(extra)}개: {extra})" if extra else ""))


if __name__ == "__main__":
    main()
