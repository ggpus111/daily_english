export const STRINGS = { ko, en }

export function createTranslator(nativeLang) {
  const strings = nativeLang === 'ko' ? ko : en
  return (key, params = {}) =>
    (strings[key] ?? key).replace(/\{(\w+)\}/g, (_, name) => params[name] ?? '')
}

export function languageName(code, nativeLang) {
  const language = LANGUAGES.find((item) => item.code === code)
  if (!language) return code
  return nativeLang === 'ko' ? language.native : language.name
}
